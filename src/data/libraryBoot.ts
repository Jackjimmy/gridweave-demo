import { loadAllAlbums } from './index'

/**
 * 开机把全库取齐，取齐了再挂树。
 *
 * 关卡库按册分块（见 data/index.ts）之后，运行时曾经有一条策略：页面先用占位挂上，
 * 画到了再就地填。这条策略与这个 App 的其余部分根本不相容——渲染与导航都假定
 * 「页面挂上之后是静态的」：首页收藏架按占位排好版再分批亮起来、收藏页第一帧
 * 只有封面、左缘返回的「上一页已画好」凭据在册块落地时悄悄失效（2026-09-15 真机
 * 三个症状，一周里为它擦了七处），全是同一件事的不同出口：**页面已经在屏幕上，
 * 内容才到**。
 *
 * 所以这里把「内容晚到」这个状态从原生端的运行时里整个删掉：挂树之前全库到齐，
 * 占位（solution 为空）在屏幕上永远不会出现，也就没有任何一处需要「到了再填」。
 * 代价量过：十六册合计约 730KB 的对象字面量，与语言资源并行取，iPhone X 上是
 * 几十毫秒的量级；分块当初省下的是主包 gzip 325→139KB，对本地文件的原生 App
 * 没有意义，构建层的分块留着无害，运行时不再按需。
 *
 * **挂树这一步不许有任何前提**（main.tsx 那条规矩）：这里永不拒绝，也不无限等。
 * 网页端弱网到点就放行，界面按占位先站起来；取册的那一趟**不会因此停下**——
 * 每一册落地照样进库、照样通知订阅方，只是晚一点。这是网页端唯一还会看到占位
 * 的情形，原生上册块是本地文件，到不了这个上限。
 */
export function preloadLibrary(timeoutMs = 1500): Promise<void> {
  return new Promise((resolve) => {
    const timer = setTimeout(resolve, timeoutMs)
    const done = () => {
      clearTimeout(timer)
      resolve()
    }
    loadAllAlbums().then(done, done)
  })
}
